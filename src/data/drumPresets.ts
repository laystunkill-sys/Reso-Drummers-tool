// Helper to create empty 16 steps
function empty16Steps(): FillPattern['steps'] {
  return Array.from({ length: 16 }, (_, i) => ({
    stepIndex: i,
    hits: {},
    sticking: i % 2 === 0 ? 'R' : 'L',
  }));
}

